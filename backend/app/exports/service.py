def _pdf_lines(snapshot):
    case = snapshot["case"]
    out = [
        "DARSON SECURITY OPERATIONS CASE REPORT",
        "Decision support; all signals require human review.",
        "",
        f"Incident: {case['incident'].get('id')}",
        f"Case version: {case['case_version']}",
        f"Tenant/site: {case['incident'].get('tenant_label')} ({case['incident'].get('tenant_id')}) / {case['incident'].get('site_label')} ({case['incident'].get('site_id')})",
        f"Category/priority: {case['incident'].get('category') or 'Unclassified'} / {case['incident'].get('priority')}",
        f"Window (local): {_local_time(case['incident'].get('start_time'), case.get('timezone'))} to {_local_time(case['incident'].get('end_time'), case.get('timezone'))}",
        f"Timezone: {case.get('timezone', 'UTC')}",
        "",
        "SUMMARY",
        case["incident"].get("summary_text") or "No summary supplied.",
        "",
        "WHY THIS CASE WAS CREATED",
    ]
    out += [str(x) for x in case.get("explanation", {}).get("why_created", [])]
    if case.get("case_study"):
        study = case["case_study"]
        out += ["", "CASE STUDY POLICY", f"Source: {study.get('source_type')} / {study.get('source_instance')}",
                f"Decision: {study.get('decision')}", f"Reason: {study.get('reason')}",
                f"Zone: {study.get('zone')}", f"Policy: {study.get('policy_version')} / {', '.join(study.get('policy_ids', [])) or 'none'}",
                f"Synthetic demo: {study.get('synthetic')}"]
    out += ["", "OBSERVATIONS / TIMELINE"]
    for item in case.get("timeline", []):
        out.append(
            f"{item.get('ts', '')} | {item.get('camera_id', '')} | {item.get('event_type', '')} | {item.get('summary', '')}"
        )
    out += ["", "BEHAVIOUR SIGNALS"]
    out += [
        json.dumps(signal, ensure_ascii=True, default=str)
        for signal in case.get("behaviour_signals", [])
    ]
    out += [
        "",
        "CORRELATION HYPOTHESES",
        "Cross-camera links describe correlated movement, not confirmed identity.",
    ]
    out += [
        json.dumps(item, ensure_ascii=True, default=str)
        for item in case.get("correlation_hypotheses", [])
    ]
    for edge in case.get("graph", {}).get("edges", []):
        if "correlation" in str(edge.get("edge_type", "")):
            out.append(json.dumps(edge, ensure_ascii=True, default=str))
    out += ["", "EVIDENCE INVENTORY"]
    for item in snapshot.get("evidence", []):
        out.append(
            f"{item.get('id')} | {item.get('status')} | SHA-256 {item.get('sha256') or 'not available'}"
        )
    out += [
        "",
        "RESPONSE / SOP / SLA",
        json.dumps(case.get("response"), ensure_ascii=True, default=str),
        json.dumps(case.get("actions", []), ensure_ascii=True, default=str),
        json.dumps(case.get("sla", []), ensure_ascii=True, default=str),
        "",
        "PROVENANCE",
        f"Export ID: {snapshot.get('export_id')}",
        f"Generated by: {snapshot.get('generated_by')}",
        f"Generated at: {snapshot.get('generated_at')}",
        f"Correlation/model version: {case.get('model_version', 'not recorded')}",
        "Scores are not calibrated probabilities and are not proof of identity, criminal activity, or wrongdoing.",
    ]
    lines = []
    for item in out:
        text = re.sub(r"[^\x20-\x7e]", "?", str(item))
        while len(text) > 92:
            split = text.rfind(" ", 0, 92)
            split = split if split > 0 else 92
            lines.append(text[:split])
            text = "  " + text[split:].lstrip()
        lines.append(text)
    return lines


def _local_time(value, zone):
    if value is None:
        return "not recorded"
    try:
        return datetime.fromtimestamp(float(value), ZoneInfo(zone or "UTC")).isoformat(
            timespec="seconds"
        )
    except Exception:
        return str(value)


def build_pdf(snapshot):
    """Create a small valid paginated PDF with built-in Helvetica fonts."""
    lines = _pdf_lines(snapshot)
    pages = [lines[i : i + 48] for i in range(0, len(lines), 48)] or [[]]
    objects = [b""]

    def add(value):
        objects.append(value if isinstance(value, bytes) else value.encode("ascii"))
        return len(objects) - 1

    catalog_id = add(b"")
    pages_id = add(b"")
    font_id = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    page_ids = []
    for page_lines in pages:
        commands = ["BT /F1 9 Tf 42 800 Td 12 TL"]
        for line in page_lines:
            escaped = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
            commands += [f"({escaped}) Tj T*"]
        commands.append("ET")
        stream = "\n".join(commands).encode("ascii")
        content_id = add(
            b"<< /Length "
            + str(len(stream)).encode()
            + b" >>\nstream\n"
            + stream
            + b"\nendstream"
        )
        page_id = add(
            f"<< /Type /Page /Parent {pages_id} 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 {font_id} 0 R >> >> /Contents {content_id} 0 R >>"
        )
        page_ids.append(page_id)
    objects[catalog_id] = f"<< /Type /Catalog /Pages {pages_id} 0 R >>".encode()
    objects[pages_id] = (
        f"<< /Type /Pages /Kids [{ ' '.join(f'{n} 0 R' for n in page_ids)}] /Count {len(page_ids)} >>"
    ).encode()
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n%DARSON\n")
    offsets = [0]
    for number, obj in enumerate(objects[1:], 1):
        offsets.append(out.tell())
        out.write(f"{number} 0 obj\n".encode())
        out.write(obj)
        out.write(b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objects)}\n0000000000 65535 f \n".encode())
    for offset in offsets[1:]:
        out.write(f"{offset:010d} 00000 n \n".encode())
    out.write(
        f"trailer\n<< /Size {len(objects)} /Root {catalog_id} 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    )
    return out.getvalue()


def process_export(db, export_id):
    row = db.get(IncidentExport, export_id)
    if not row or row.status == "ready":
        return
    row.status = "generating"
    db.commit()
    snapshot = row.snapshot
    case = snapshot["case"]
    pdf = build_pdf(snapshot)
    if row.format == "pdf":
        content = pdf
    else:
        target = io.BytesIO()
        with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            archive.writestr(
                "manifest.json",
                json.dumps(
                    {
                        "export_id": snapshot.get("export_id"),
                        "case_version": snapshot.get("case_version"),
                        "generated_by": snapshot.get("generated_by"),
                        "generated_at": snapshot.get("generated_at"),
                        "case_sha256": digest(case),
                    },
                    indent=2,
                ),
            )
            archive.writestr(
                "case.json", json.dumps(case, ensure_ascii=False, indent=2, default=str)
            )
            archive.writestr(
                "timeline.json",
                json.dumps(
                    case.get("timeline", []), ensure_ascii=False, indent=2, default=str
                ),
            )
            archive.writestr("report.pdf", pdf)
            evidence_manifest = []
            for item in snapshot.get("evidence", []):
                record = {
                    k: item.get(k)
                    for k in ("id", "kind", "status", "sha256", "mime", "size")
                }
                provenance_keys = (
                    "source_instance",
                    "source_event",
                    "source_type",
                    "camera",
                    "source_timestamp",
                    "source_start",
                    "source_end",
                    "ingest_timestamp",
                    "time_sync_uncertainty_seconds",
                    "policy_version",
                    "media_origin",
                    "captured_at",
                    "expires_at",
                    "sha256",
                    "bytes",
                    "mime",
                )
                record["provenance"] = {
                    key: item.get("manifest", {}).get(key)
                    for key in provenance_keys
                    if key in item.get("manifest", {})
                }
                if item.get("status") == "available" and item.get("object_key"):
                    try:
                        data = ObjectStore().read(db.info["scope"], item["object_key"])
                        actual = hashlib.sha256(data).hexdigest()
                    except (FileNotFoundError, OSError, ValueError):
                        record["status"] = "missing"
                    else:
                        if actual != item.get("sha256"):
                            record["status"] = "integrity-failed"
                        else:
                            suffix = {
                                "image/jpeg": "jpg",
                                "image/png": "png",
                                "video/mp4": "mp4",
                            }.get(item.get("mime"), "bin")
                            archive.writestr(f"evidence/{item['id']}.{suffix}", data)
                            record["package_path"] = f"evidence/{item['id']}.{suffix}"
                evidence_manifest.append(record)
            archive.writestr(
                "evidence-manifest.json", json.dumps(evidence_manifest, indent=2)
            )
        content = target.getvalue()
    key = ObjectStore().put(db.info["scope"], content)
    row.object_key, row.sha256, row.size = (
        key,
        hashlib.sha256(content).hexdigest(),
        len(content),
    )
    row.status, row.completed_at, row.failure_class = "ready", time.time(), None
    db.commit()
